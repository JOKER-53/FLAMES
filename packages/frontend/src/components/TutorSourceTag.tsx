// Tells students whether a hint or question came from the live AI tutor or the
// built-in fallback, so offline content is never presented as AI-generated.
export type TutorSource = "ai" | "guide" | "bank";

const LABELS: Record<TutorSource, { text: string; title: string; color: string; background: string }> = {
  ai:    { text: "AI tutor",       title: "Generated by the AI tutor for this attempt.", color: "#6d28d9", background: "#ede9fe" },
  guide: { text: "Guided hint",    title: "The AI tutor is unavailable, so this is a built-in hint for this topic.", color: "#475569", background: "#e2e8f0" },
  bank:  { text: "Question bank",  title: "The AI tutor is unavailable, so this question comes from the curated question bank.", color: "#475569", background: "#e2e8f0" },
};

export function TutorSourceTag({ source }: { source: TutorSource | null | undefined }) {
  if (!source) return null;
  const label = LABELS[source];
  return (
    <span title={label.title} style={{ marginLeft: 6, fontSize: 10, fontWeight: 600, padding: "1px 6px", borderRadius: 3, color: label.color, background: label.background, verticalAlign: "middle" }}>
      {label.text}
    </span>
  );
}
